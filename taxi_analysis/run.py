"""Run the full pipeline for one month.

    python -m taxi_analysis.run --month 2024-01

Reads data/raw/, writes tables, charts and a written report to output/<month>/.
"""

import argparse
import sys
import time
from pathlib import Path

import pandas as pd

from taxi_analysis import charts
from taxi_analysis.analysis import add_features, run_queries
from taxi_analysis.load import get_spark, read_trips, read_zones
from taxi_analysis.quality import build_rules, flag_trips, summarise

PROJECT_DIR = Path(__file__).resolve().parent.parent
RAW_DIR = PROJECT_DIR / "data" / "raw"


def find_trips_file(month: str) -> Path:
    for suffix in (".parquet", ".csv.gz", ".csv"):
        candidate = RAW_DIR / f"yellow_tripdata_{month}{suffix}"
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        f"No trips file for {month} in {RAW_DIR}. Run: python scripts/download_data.py --month {month}"
    )


def md_table(df: pd.DataFrame) -> str:
    """Minimal markdown table (avoids an extra dependency)."""
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.2f}".rstrip("0").rstrip(".") if abs(v) < 1e15 else str(v)
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)

    header = "| " + " | ".join(df.columns) + " |"
    rule = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def write_report(month: str, source: str, dq: dict, results: dict, out: Path, seconds: float) -> None:
    head = results["headline"].iloc[0]
    demand = results["demand_by_weekday_hour"]
    busiest = demand.loc[demand["avg_trips_per_day"].idxmax()]
    quietest = demand.loc[demand["avg_trips_per_day"].idxmin()]
    tips = results["tips_by_hour"]
    tip_high = tips.loc[tips["median_tip_pct"].idxmax()]
    tip_low = tips.loc[tips["median_tip_pct"].idxmin()]
    dropped = dq["total"] - dq["kept"]

    dq_table = pd.DataFrame(dq["rules"])[["description", "failed", "failed_pct"]]
    # A rule that caught a handful of trips should not read as "0%".
    dq_table["failed_pct"] = [
        "0" if failed == 0 else ("<0.01" if pct < 0.01 else f"{pct:.2f}")
        for failed, pct in zip(dq_table["failed"], dq_table["failed_pct"])
    ]
    dq_table.columns = ["Rule", "Trips caught", "% of raw trips"]

    lines = [
        f"# NYC yellow taxi trips, {month}",
        "",
        f"Source file: `{source}`. Generated by `python -m taxi_analysis.run --month {month}` "
        f"in {seconds:,.0f} seconds.",
        "",
        "## Headline",
        "",
        f"- **{dq['total']:,}** raw trips; **{dq['kept']:,}** kept after data-quality checks "
        f"({100 * dq['kept'] / dq['total']:.1f}%), **{dropped:,}** removed.",
        f"- Average fare **${head['avg_fare_usd']:.2f}**, average distance **{head['avg_distance_mi']:.2f} mi**, "
        f"median trip **{head['median_duration_min']:.1f} min**.",
        f"- **{head['card_share_pct']:.1f}%** of trips were paid by credit card.",
        f"- Busiest slot: **{busiest['pickup_day_name']} {int(busiest['pickup_hour']):02d}:00** "
        f"({busiest['avg_trips_per_day']:,.0f} trips per day on average). "
        f"Quietest: **{quietest['pickup_day_name']} {int(quietest['pickup_hour']):02d}:00** "
        f"({quietest['avg_trips_per_day']:,.0f}).",
        f"- Median card tip peaks at **{tip_high['median_tip_pct']:.1f}%** of the fare at "
        f"{int(tip_high['pickup_hour']):02d}:00 and is lowest at **{tip_low['median_tip_pct']:.1f}%** "
        f"at {int(tip_low['pickup_hour']):02d}:00.",
        "",
        "## Data quality",
        "",
        "Each rule is checked on every raw trip; a trip can fail more than one rule, so the counts "
        "can add up to more than the trips removed.",
        "",
        md_table(dq_table),
        "",
        "## Demand by weekday and hour",
        "",
        "![Demand heatmap](charts/demand_heatmap.png)",
        "",
        "## Pickup boroughs",
        "",
        md_table(results["borough_summary"]),
        "",
        "## Top pickup zones",
        "",
        "![Top pickup zones](charts/top_pickup_zones.png)",
        "",
        md_table(results["top_pickup_zones"].head(10)),
        "",
        "## Airport trips",
        "",
        "Trips that start or end at JFK, LaGuardia or Newark.",
        "",
        md_table(results["airport_trips"]),
        "",
        "## Payments and tips",
        "",
        md_table(results["payment_mix"]),
        "",
        "Tips are recorded only for card payments, so tip figures use credit-card trips alone.",
        "",
        "![Median tip by hour](charts/tips_by_hour.png)",
        "",
    ]
    (out / "report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="NYC taxi PySpark pipeline")
    parser.add_argument("--month", required=True, help="Month to analyse, as YYYY-MM")
    args = parser.parse_args()

    started = time.time()
    trips_path = find_trips_file(args.month)
    zones_path = RAW_DIR / "taxi_zone_lookup.csv"
    out = PROJECT_DIR / "output" / args.month
    (out / "tables").mkdir(parents=True, exist_ok=True)
    (out / "charts").mkdir(parents=True, exist_ok=True)

    spark = get_spark()
    spark.sparkContext.setLogLevel("ERROR")
    try:
        print(f"Reading {trips_path.name}")
        raw = read_trips(spark, str(trips_path))
        zones = read_zones(spark, str(zones_path))

        rules = build_rules(args.month)
        flagged = flag_trips(raw, rules).cache()
        print("Running data-quality checks")
        dq = summarise(flagged, rules)
        print(f"  {dq['total']:,} raw trips, {dq['kept']:,} kept")

        clean = add_features(flagged.filter("dq_pass")).cache()
        print("Running analysis queries")
        results = run_queries(spark, clean, zones)

        for name, table in results.items():
            table.to_csv(out / "tables" / f"{name}.csv", index=False)
        pd.DataFrame(dq["rules"]).to_csv(out / "tables" / "data_quality.csv", index=False)

        charts.demand_heatmap(results["demand_by_weekday_hour"], args.month, out / "charts" / "demand_heatmap.png")
        charts.top_zones_bar(results["top_pickup_zones"], args.month, out / "charts" / "top_pickup_zones.png")
        charts.tips_line(results["tips_by_hour"], args.month, out / "charts" / "tips_by_hour.png")

        write_report(args.month, trips_path.name, dq, results, out, time.time() - started)
        print(f"Done. Report: {out / 'report.md'}")
    finally:
        spark.stop()
    return 0


if __name__ == "__main__":
    sys.exit(main())
